const fs = require('node:fs');
const path = require('node:path');
const {parseHTML} = require('linkedom');

const origin = 'https://vakithesaplama.diyanet.gov.tr';
const normalize = text => text.toLocaleUpperCase('tr-TR').normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/İ/g,'I').replace(/\s+/g,' ').trim();
const months = ['OCAK','SUBAT','MART','NISAN','MAYIS','HAZIRAN','TEMMUZ','AGUSTOS','EYLUL','EKIM','KASIM','ARALIK'];
async function page(url) {
  if (new URL(url).origin !== origin) throw new Error('Only the official Diyanet origin is allowed');
  const response = await fetch(url,{signal:AbortSignal.timeout(20000)});
  if (!response.ok) throw new Error(`${response.status}: ${url}`);
  const bytes = await response.arrayBuffer();
  const encoding = response.headers.get('content-type')?.match(/charset=([\w-]+)/i)?.[1] || 'utf-8';
  return parseHTML(new TextDecoder(encoding).decode(bytes)).document;
}
async function main() {
  const index = await page(origin+'/icerik.php?icerik=159');
  const urls = new Map();
  for(const link of index.querySelectorAll('a[href]')) {
    const label = normalize(link.textContent);
    const year = Number(label.match(/20\d{2}/)?.[0]);
    if (year >= 2025 && year <= 2035 && /RESMI TATIL/.test(label)) urls.set(year,new URL(link.getAttribute('href'),origin).href);
  }
  if (!urls.has(2026) || !urls.has(2027)) throw new Error('Official year links were not found');
  const years={};
  for (const [year,url] of [...urls].sort((a,b)=>a[0]-b[0])) {
    const document=await page(url);
    if (!new RegExp(`${year}\\s*YILI\\s*RESMI\\s*TATIL\\s*GUNLERI`).test(normalize(document.documentElement.textContent))) { console.log(`Unpublished/empty calendar skipped: ${url}`); continue; }
    const dates={ramazan:[],kurban:[]};
    for(const row of document.querySelectorAll('tr')) {
      const cells=Array.from(row.querySelectorAll('td')).map(cell=>normalize(cell.textContent));
      if(cells.length!==4 || cells[1]!=='1. GUN') continue;
      const key=cells[0]==='RAMAZAN BAYRAMI'?'ramazan':cells[0]==='KURBAN BAYRAMI'?'kurban':null;
      if(!key) continue;
      const parts=cells[2].match(/^(\d{1,2})\s+([A-Z]+)/);
      const month=parts ? months.indexOf(parts[2])+1 : 0;
      if(!month) throw new Error(`Unrecognized date on ${url}: ${cells[2]}`);
      const date=`${year}-${String(month).padStart(2,'0')}-${parts[1].padStart(2,'0')}`;
      if(new Date(date+'T00:00:00Z').toISOString().slice(0,10)!==date) throw new Error('Invalid date '+date);
      if(!dates[key].includes(date)) dates[key].push(date);
    }
    if(!dates.ramazan.length || !dates.kurban.length || dates.ramazan.length>2 || dates.kurban.length>2) throw new Error(`Incomplete official table for ${year}`);
    years[year]={...dates,source:url};
    console.log(year,dates.ramazan.join(','),dates.kurban.join(','));
  }
  if (!years[2026] || !years[2027]) throw new Error('Current and next year could not be verified; keeping the previous data file');
  const previous=require('../ogretmen-ajandasi/resmi-tatiller-veri.js');
  if (Object.keys(previous.years).some(year=>!years[year])) throw new Error('An existing published year could not be verified; keeping the previous file');
  const data={version:1,verifiedAt:new Date().toISOString().slice(0,10),authority:'T.C. Diyanet İşleri Başkanlığı',law:origin+'/2429_kanun.php',years};
  const source='// Generated by scripts/update-agenda-holidays.cjs from official published calendars.\n'
    + '(function(root){const data='+JSON.stringify(data,null,2)+';if(typeof module==="object"&&module.exports)module.exports=data;else root.KemalOfficialHolidayData=data;})(typeof window!=="undefined"?window:globalThis);\n';
  fs.writeFileSync(path.resolve(__dirname,'../ogretmen-ajandasi/resmi-tatiller-veri.js'),source);
}
main().catch(error=>{console.error(error);process.exitCode=1;});
