const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const base = path.join(__dirname, '../src/platform');
const input = fs.readFileSync(path.join(base, 'activity-bridge.ts'), 'utf8');
const parsed = ts.createSourceFile('activity-bridge.ts', input, ts.ScriptTarget.Latest, true);
const install = parsed.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === 'install');
if (!install) throw new Error('Native bridge source is missing.');
const compiled = ts.transpileModule(install.getFullText(parsed), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.None } }).outputText;
const emitted = ts.createSourceFile('activity-bridge.js', compiled, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
const functionNode = emitted.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === 'install');
if (!functionNode) throw new Error('Native bridge compilation failed.');
const js = functionNode.getText(emitted);
new (require('node:vm').Script)('(' + js + ');');
const output = '// Generated by scripts/build-bridge.cjs. Do not edit by hand.\n// Static text is required: Hermes Function.toString does not preserve source.\nexport const activityBridgeSource = ' + JSON.stringify(js) + ';\n';
const dest = path.join(base, 'bridgeSource.ts');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== output) throw new Error('Run npm run bridge:generate before building.');
} else fs.writeFileSync(dest, output);
